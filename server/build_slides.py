        "-fill", "#1e293b", "-stroke", "#334155", "-strokewidth", "1", "-draw", "roundrectangle 1550,56,1830,94,6,6",
        "-font", fb, "-pointsize", "13", "-fill", "#38bdf8", "-stroke", "none", "-draw", f"text 1570,79 '{badge}'",
